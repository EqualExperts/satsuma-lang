#!/usr/bin/env node
/**
 * Generate core's public TypeScript contract from tree-sitter node-types.json.
 *
 * The grammar package owns symbol discovery; this module deliberately knows
 * nothing about extraction or consumer behaviour. Its check mode writes to a
 * temporary file so detecting drift never mutates the tracked artifact.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const PACKAGE_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "..");
const DEFAULT_NODE_TYPES_PATH = path.join(PACKAGE_ROOT, "src", "node-types.json");
const DEFAULT_OUTPUT_PATH = path.resolve(
  PACKAGE_ROOT,
  "..",
  "satsuma-core",
  "src",
  "generated",
  "cst-types.ts",
);
const GENERATED_FILE_NOTICE = "Generated by tree-sitter-satsuma/scripts/generate-cst-symbols.mjs";
// Tree-sitter synthesizes ERROR for unexpected input, so it is absent from
// node-types.json but must be part of the runtime node contract. Missing nodes
// keep the expected grammar symbol and report missingness through isMissing.
const RECOVERY_NODE_TYPE = "ERROR";

/**
 * Split tree-sitter node descriptors into stable, independently sorted symbol families.
 *
 * @param {unknown} nodeTypes parsed contents of node-types.json
 * @returns {{ namedKinds: string[], anonymousTokens: string[] }} grammar symbols by family
 */
export function classifyNodeTypes(nodeTypes) {
  if (!Array.isArray(nodeTypes)) {
    throw new TypeError("node-types.json must contain an array");
  }

  const namedKinds = [];
  const anonymousTokens = [];
  const seenSymbols = new Set();

  for (const [index, nodeType] of nodeTypes.entries()) {
    if (
      nodeType === null ||
      typeof nodeType !== "object" ||
      typeof nodeType.type !== "string" ||
      typeof nodeType.named !== "boolean"
    ) {
      throw new TypeError(`node-types.json entry ${index} must have string type and boolean named`);
    }
    if (seenSymbols.has(nodeType.type)) {
      throw new Error(`node-types.json contains duplicate symbol ${JSON.stringify(nodeType.type)}`);
    }

    seenSymbols.add(nodeType.type);
    (nodeType.named ? namedKinds : anonymousTokens).push(nodeType.type);
  }

  namedKinds.sort(compareCodeUnits);
  anonymousTokens.sort(compareCodeUnits);
  return { namedKinds, anonymousTokens };
}

/**
 * Render the complete public contract without relying on a formatter.
 *
 * @param {{ namedKinds: string[], anonymousTokens: string[] }} symbols classified grammar symbols
 * @returns {string} deterministic TypeScript source ending in one newline
 */
export function renderCstSymbolContract({ namedKinds, anonymousTokens }) {
  return `/**
 * ${GENERATED_FILE_NOTICE}.
 *
 * Do not edit this file directly. Run \`npm run generate\` in the grammar
 * package after changing grammar.js, then commit the refreshed contract.
 */

/** Named CST node kinds emitted by the Satsuma grammar. */
export const SATSUMA_NAMED_KINDS = ${renderReadonlyTuple(namedKinds)};

/** Anonymous grammar tokens that can also appear as concrete CST nodes. */
export const SATSUMA_ANONYMOUS_TOKENS = ${renderReadonlyTuple(anonymousTokens)};

/** Every symbol declared by the generated Satsuma grammar. */
export const SATSUMA_GRAMMAR_SYMBOLS = [
  ...SATSUMA_NAMED_KINDS,
  ...SATSUMA_ANONYMOUS_TOKENS,
] as const;

/** Runtime recovery nodes use ERROR even though it is not a grammar symbol. */
export const SATSUMA_RECOVERY_TYPE = ${JSON.stringify(RECOVERY_NODE_TYPE)} as const;

/** Every concrete node type that the parser can return. */
export const SATSUMA_CST_TYPES = [...SATSUMA_GRAMMAR_SYMBOLS, SATSUMA_RECOVERY_TYPE] as const;

/** A named node kind declared by the grammar. */
export type SatsumaNamedKind = (typeof SATSUMA_NAMED_KINDS)[number];

/** An anonymous token declared by the grammar. */
export type SatsumaAnonymousToken = (typeof SATSUMA_ANONYMOUS_TOKENS)[number];

/** Any named or anonymous symbol declared by the grammar. */
export type SatsumaGrammarSymbol = SatsumaNamedKind | SatsumaAnonymousToken;

/**
 * Any node type observable on a parsed tree.
 *
 * Tree-sitter represents an unexpected construct with ERROR. A missing node
 * instead retains the expected grammar symbol and sets SyntaxNode.isMissing,
 * so MISSING is deliberately not a separate string member of this contract.
 */
export type SatsumaCstType = SatsumaGrammarSymbol | ${JSON.stringify(RECOVERY_NODE_TYPE)};
`;
}

/**
 * Read node-types.json and write its TypeScript contract to the requested path.
 *
 * @param {{ nodeTypesPath?: string, outputPath?: string }} paths optional source and destination
 * @returns {string} generated TypeScript source
 */
export function generateCstSymbolContract({
  nodeTypesPath = DEFAULT_NODE_TYPES_PATH,
  outputPath = DEFAULT_OUTPUT_PATH,
} = {}) {
  const nodeTypes = JSON.parse(fs.readFileSync(nodeTypesPath, "utf8"));
  const output = renderCstSymbolContract(classifyNodeTypes(nodeTypes));
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, output);
  return output;
}

/**
 * Fail when the tracked artifact differs from freshly generated temporary output.
 *
 * @param {{ nodeTypesPath?: string, outputPath?: string }} paths optional source and tracked file
 */
export function checkGeneratedContract({
  nodeTypesPath = DEFAULT_NODE_TYPES_PATH,
  outputPath = DEFAULT_OUTPUT_PATH,
} = {}) {
  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "satsuma-cst-contract-"));
  const temporaryOutputPath = path.join(temporaryDirectory, "cst-types.ts");

  try {
    generateCstSymbolContract({ nodeTypesPath, outputPath: temporaryOutputPath });
    const generated = fs.readFileSync(temporaryOutputPath, "utf8");
    const tracked = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
    if (tracked !== generated) {
      throw new Error(
        `Generated CST symbol contract is stale: ${outputPath}\n` +
          "Run `npm run generate` in tooling/tree-sitter-satsuma and commit the result.",
      );
    }
  } finally {
    fs.rmSync(temporaryDirectory, { recursive: true, force: true });
  }
}

function renderReadonlyTuple(symbols) {
  if (symbols.length === 0) return "[] as const";
  if (symbols.length === 1) return `[${JSON.stringify(symbols[0])}] as const`;
  return `[\n${symbols.map((symbol) => `  ${JSON.stringify(symbol)},`).join("\n")}\n] as const`;
}

function compareCodeUnits(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function parseArguments(arguments_) {
  let check = false;
  let outputPath = DEFAULT_OUTPUT_PATH;

  for (let index = 0; index < arguments_.length; index += 1) {
    const argument = arguments_[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--output") {
      const requestedPath = arguments_[index + 1];
      if (requestedPath === undefined) throw new Error("--output requires a file path");
      outputPath = path.resolve(requestedPath);
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }

  return { check, outputPath };
}

function runCli() {
  const { check, outputPath } = parseArguments(process.argv.slice(2));
  if (check) {
    checkGeneratedContract({ outputPath });
    process.stdout.write(`Generated CST symbol contract is current: ${outputPath}\n`);
  } else {
    generateCstSymbolContract({ outputPath });
    process.stdout.write(`Generated CST symbol contract: ${outputPath}\n`);
  }
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === SCRIPT_PATH) {
  try {
    runCli();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
